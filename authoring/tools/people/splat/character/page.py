def say_number(k, v):
    k = k.replace('_', ' ')
    if k.endswith(' db'):
        return f"{k[:-3]} {v:.2f} dB"
    return f"{k} {v:,}" if isinstance(v, int) else f"{k} {v}"


def items_html(m, k):
    """A stage's ledger as a table, finals first. On a bound character's page the table holds what matters for the bound route
    (final, alternates, source, evidence); working files, superseded attempts and the earlier free bake fold away below it."""
    items = m['stages'][k].get('items') or []
    if not items:
        return ''
    d = dc.char_dir(m['id']); bound = is_bound(m)

    def row(i):
        bg, fg = ROLE_COLOURS[i['role']]; p = i['path']; inside = not os.path.isabs(p)
        where = f"<a href='{esc(p)}{'/' if (d / p).is_dir() else ''}'>{esc(p)}</a>" if inside else f"<span class='muted'>{esc(rel(p))} (not in this folder)</span>"
        nums = ' · '.join(say_number(a, b) for a, b in (i.get('numbers') or {}).items())
        links = ' · '.join(f"<a href='{esc(u)}'>{esc(l)}</a>" for l, u in (i.get('links') or {}).items())
        return (f"<tr><td class='n'><span class='role' style='background:{bg};color:{fg}' title='{esc(dc.ROLES[i['role']])}'>{esc(i['role'])}</span></td>"
                f"<td class='n'><b>{esc(i['name'])}</b></td><td>{esc(i['what'])}{('<div>' + esc(nums) + '</div>') if nums else ''}"
                f"{('<div>' + links + '</div>') if links else ''}{('<div class=muted>made from: ' + esc(i['made_from']) + '</div>') if i.get('made_from') else ''}</td>"
                f"<td>{where}</td></tr>")

    def table(its, routes):
        rows = []
        for route in [r for r in list(dc.ROUTES) + [None] if any(i.get('route') == r for i in its)]:
            if routes:
                rows.append(f"<tr class='route'><td colspan='4'>{esc(dc.ROUTES.get(route, 'both routes'))}</td></tr>")
            rows += [row(i) for i in sorted((i for i in its if i.get('route') == route), key=lambda i: ROLE_ORDER.index(i['role']))]
        return "<table class='items'><tr><th>role</th><th>item</th><th>what it is</th><th>where</th></tr>" + ''.join(rows) + '</table>'

    if not bound:
        return '<b>What is here</b>' + table(items, True)
    main = [i for i in items if i.get('route') != 'free' and i['role'] in SHOWN]
    work = [i for i in items if i.get('route') != 'free' and i['role'] not in SHOWN]; free = [i for i in items if i.get('route') == 'free']
    out = ('<b>What is here</b>' + table(main, False)) if main else ''
    if work:
        out += f"<details><summary class='muted'>working files and superseded attempts ({len(work)})</summary>{table(work, False)}</details>"
    if free:
        out += f"<details><summary class='muted'>the earlier free bake ({len(free)}; kept, not this route)</summary>{table(free, False)}</details>"
    return out


def rel(p):
    """A path as a person reads it over the share: relative to the repository when it is inside it."""
    p = str(p)
    return os.path.relpath(p, dc.REPO) if p.startswith(str(dc.REPO)) else p


