def key_number(st, k, bound=False):
    c = st.get('checks') or {}; r = (st.get('review') or {}).get('marks') or []
    if bound:
        num = lambda name: next((i.get('numbers') or {} for i in st.get('items', []) if i['name'] == name), {})
        if k == '02-guide' and num('rigged scaffold'):
            return f"outline IoU {num('rigged scaffold').get('outline_iou')}"
        if k == '08-final' and num('bound bake'):
            return f"bound, held back {num('bound bake').get('held_back_db'):.2f} dB"
        if k == '09-game' and st.get('bound_final'):
            return f"runtime body: {st['bound_final']['size'].replace('-', ' ')}"
    marked = [x for x in r if x['mark'] in ('good', 'bad', 'maybe')]
    if k in ('01-concept',) and marked:
        return f"Patch: {marked[-1]['mark']}"
    if k == '03-clip':
        sel = st.get('selected') or []
        if sel and isinstance(sel[0], dict):
            return ' + '.join(f"{x.get('role') or 'role not recorded'} {x.get('frames')} fr {x.get('size') or ''}" for x in sel) + (f" · Patch: {marked[-1]['mark']}" if marked else '')
        return f"Patch: {marked[-1]['mark']}" if marked else ''
    if k == '04-cutouts' and c:
        return f"{c.get('frames_with_holes_removed', 0)} frames opened, {c.get('removed_px', 0):,} px"
    if k in ('06-first-fit', '07-refine') and c.get('heldout_subject_psnr'):
        return f"held-out {c['heldout_subject_psnr']:.2f} dB"
    if k == '08-final' and c.get('frame_lean_deg') is not None:
        return f"lean {c['frame_lean_deg']}°"
    if k == '09-game' and c.get('glbs'):
        return f"{len(c['glbs'])} GLBs"
    return ''


def since(st):
    w = st.get('waiting_since') or st.get('updated') or ''
    return w[:10]


def why(m, k):
    """The few words a cell shows when it is not approved: the failing check and its number, or what it waits on."""
    st = m['stages'][k]; state = st['state']; stl = dc.stale(m, k)
    if stl:
        return 'stale: ' + stl[0]
    if state == 'needs-Patch':
        return f"waiting on Patch since {since(st)}" + (f" - {st['why']}" if st.get('why') else '')
    if state in ('needs-check', 'failed', 'on-hold', 'rejected', 'skipped', 'running'):
        return st.get('why') or st.get('note', '')[:70]
    if state == 'empty':
        i = dc.STAGE_KEYS.index(k); prev = next((p for p in reversed(dc.STAGE_KEYS[:i]) if m['stages'][p]['state'] != 'skipped'), None)
        if prev and m['stages'][prev]['state'] not in ('approved',) and (i == 0 or m['stages'][dc.STAGE_KEYS[i - 1]]['state'] != 'empty'):
            return f"waits for {prev[3:]}"
        return st.get('note', '')[:70] if i and m['stages'][dc.STAGE_KEYS[i - 1]]['state'] != 'empty' else ''
    return ''


def attention(ms):
    """failed, needs-check, needs-Patch and stale stages across all characters, oldest first."""
    rows = []
    for m in ms:
        for k, title, _, _ in dc.STAGES:
            st = m['stages'][k]; stl = dc.stale(m, k)
            if st['state'] in ('failed', 'needs-check', 'needs-Patch') or stl:
                rows.append((st.get('waiting_since') or st.get('updated') or '', m['id'], k, 'stale' if stl and st['state'] == 'approved' else st['state'], why(m, k)))
    return sorted(rows)


def esc(x):
    return html.escape(str(x))


def eyes_of(fin, cid):
    """The blink mask of a character's Engine GLB (eye_mask.py, rusty-dagger #10977): its _GROUP, lid colour and eye Gaussian count
    from the GLB's asset.extras.eyes, the remnant left in the shut eye and any failed check from the report (ID-eyes.json beside the
    GLB, or the 24 townspeople's run in asset-pipeline live-evidence/eye-masks-20261122-r01/reports). None without a mask."""
    g = fin / f'{cid}.glb'
    if not g.exists():
        return None
    b = g.read_bytes(); n = int.from_bytes(b[12:16], 'little')
    e = json.loads(b[20:20 + n])['asset'].get('extras', {}).get('eyes')
    if not e:
        return None
    rep = next((r for r in (fin / f'{cid}-eyes.json', dc.AP / 'live-evidence/eye-masks-20261122-r01/reports' / f'{cid}-eyes.json') if r.exists()), None)
    rem, flag = None, None
    if rep:
        r = json.loads(rep.read_text()); rem = r['rounds'][-1]['remnant_share'] if r.get('rounds') else None
        words = {'remnant_under_5pct': 'small iris/eye-white remnant when shut (large skin Gaussians); see contact sheet'}
        bad = [words.get(k, k) for k, ok in r.get('checks', {}).items() if not ok]; flag = ', '.join(bad) or None
    return {'group': e['group'], 'lid': e['lid'], 'gaussians': e['gaussians'], 'remnant_share': rem, 'flag': flag}


def ready(root, ms):
    """Characters whose 09-game stage is approved (Patch passed the playable set): ready for game testing. The rest, with the stage that holds them."""
    out, wait = [], []
    for m in ms:
        g = m['stages']['09-game']; bf = g.get('bound_final') or {}
        if g['state'] == 'approved' and not dc.stale(m, '09-game'):
            fin = Path(root) / m['id'] / '09-game/bound/final'
            man = fin / 'character.json'
            out.append({'id': m['id'], 'name': m['name'], 'runtime_body': bf.get('size') or g.get('note', '').split('runtime body: ')[-1].split(' ')[0].rstrip('.'),
                        'folder': f"{m['id']}/09-game/bound/final" if fin.exists() else None,
                        'playable': (f"{m['id']}/09-game/bound/final/character.json" if man.exists() else None),
                        'engine_glb': (f"{m['id']}/09-game/bound/final/{m['id']}.glb" if (fin / f"{m['id']}.glb").exists() else None),
                        'patch_said': bf.get('said', ''), 'approved_on': bf.get('on') or (g.get('updated') or '')[:10], 'note': g.get('note', '')})
            ey = eyes_of(fin, m['id'])
            if ey:
                out[-1]['eyes'] = ey
            if (fin / f"{m['id']}.core.glb").exists():   # the Engine GLB with the matte inset core as a second primitive (rusty-engine #10990's contract; npc-023, Patch 2026-11-23)
                out[-1]['core_glb'] = f"{m['id']}/09-game/bound/final/{m['id']}.core.glb"
            gj = fin / f"{m['id']}.glb.json"
            if gj.exists() and json.loads(gj.read_text()).get('static'):   # a static NPC: not a walker; ID-idle.glb and ID-look.glb are its clips
                out[-1].update({'static': True, 'clips': {c: f"{m['id']}/09-game/bound/final/{m['id']}-{c}.glb" for c in ('idle', 'look')}})
        else:
            k = ([k for k, *_ in dc.STAGES if m['stages'][k]['state'] != 'empty'] or [dc.STAGES[0][0]])[-1]   # the furthest stage with work in it (the first for a fresh one, e.g. 397-B)
            wait.append({'id': m['id'], 'name': m['name'], 'held_at': k, 'state': m['stages'][k]['state'], 'note': m['stages'][k].get('note', '')[:200]})
    return out, wait


