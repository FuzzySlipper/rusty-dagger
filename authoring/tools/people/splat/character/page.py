def check_images(root):
    """Every image and video the pages reference must exist and load; returns the problems (the command fails on any)."""
    import re
    from PIL import Image
    bad = []
    for pg in [root / 'index.html'] + sorted(root.glob('*/index.html')):
        for ref in re.findall(r"(?:src|href)='([^']+\.(?:png|jpg|jpeg|mp4))'", pg.read_text()):
            f = (pg.parent / html.unescape(ref)).resolve()
            if not f.exists():
                bad.append(f'{rel(pg)}: {ref} missing'); continue
            if f.suffix == '.mp4':
                if frames(f) in ('', '?', '0'):
                    bad.append(f'{rel(pg)}: {ref} does not decode')
                continue
            try:
                Image.open(f).verify()
            except Exception as e:
                bad.append(f'{rel(pg)}: {ref} does not load ({e})')
    return bad


