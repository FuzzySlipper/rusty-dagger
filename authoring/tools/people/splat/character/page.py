def is_bound(m):
    return m.get('recipe') == 'bound-scaffold'


def thumb(cid, stage, src):
    """A small JPEG of an image (or a video's first frame), cached under ID/.page/, rebuilt when the source is newer."""
    if not src or not Path(src).exists():
        return None
    out = dc.char_dir(cid) / 'thumbnails' / f'{stage}.jpg'; out.parent.mkdir(exist_ok=True); was = out.with_suffix('.src')
    if not out.exists() or out.stat().st_mtime < Path(src).stat().st_mtime or not was.exists() or was.read_text() != str(src):
        was.write_text(str(src))
        if str(src).endswith('.mp4'):
            subprocess.run(['ffmpeg', '-loglevel', 'error', '-y', '-i', str(src), '-frames:v', '1', '-vf', 'scale=-2:240', str(out)])
        else:
            from PIL import Image
            im = Image.open(src).convert('RGB')
            if im.width > 2.2 * im.height:   # a strip of views (review sheets): its first two views read better than all of them shrunk
                im = im.crop((0, 0, 2 * im.height, im.height))
            im.thumbnail((480, 240)); im.save(out, quality=85)
    return f'thumbnails/{stage}.jpg' if out.exists() else None


def first(*paths):
    for p in paths:
        hits = sorted(Path().glob(str(p))) if any(c in str(p) for c in '*?[') else ([Path(p)] if Path(p).exists() else [])
        if hits:
            return hits[0]
    return None


