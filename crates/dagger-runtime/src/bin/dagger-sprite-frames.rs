//! dagger-sprite-frames: runtime-authoritative sprite frame service.
//!
//! Owns BOTH directional enemy orientation (camera-driven, via
//! `evaluate_directional`) AND environment flat animation (time-cycled,
//! via `AnimationService`). Consumers never re-implement the math.
//!
//! One-shot (directional only, for static proofs):
//!   dagger-sprite-frames <scene.json> <cam-x,cam-y,cam-z>...
//!   stdout: {"enemyCount":N,"poses":[{"camera":[...],"assignments":[{"index":I,"frame":F}]}]}
//!
//! Live server (consolidated authority for both sprite kinds):
//!   dagger-sprite-frames <enemies.json> --serve <host:port>
//!   GET /updates?cam=x,y,z -> {"updates":[{"handle":H,"frame":F}]}
//!
//! The live server owns an AnimationService: each request advances elapsed
//! time from wall-clock and evaluates all registered sprites (enemies +
//! animated billboards), returning a single consolidated frame diff. The
//! flycam polls this endpoint and applies the result in one applyFrame.

use dagger_runtime::{evaluate_directional, AnimationService, FrameUpdate, PatrolService};
use std::io::{BufRead, BufReader, Write};
use std::net::TcpListener;
use std::time::Instant;

fn parse_camera(arg: &str) -> [f32; 3] {
    parse_camera_opt(arg).unwrap_or_else(|| {
        eprintln!("bad camera {arg:?}; expected x,y,z");
        std::process::exit(2);
    })
}

fn parse_camera_opt(arg: &str) -> Option<[f32; 3]> {
    let parts: Vec<&str> = arg.split(',').collect();
    if parts.len() != 3 {
        return None;
    }
    let mut out = [0.0f32; 3];
    for (i, part) in parts.iter().enumerate() {
        out[i] = part.parse().ok()?;
    }
    Some(out)
}

// --- One-shot mode: scene.json directional frames (static proofs) ---------

fn load_enemy_positions(scene_path: &str) -> Vec<[f32; 3]> {
    let text = std::fs::read_to_string(scene_path).unwrap_or_else(|e| {
        eprintln!("read {scene_path}: {e}");
        std::process::exit(1);
    });
    let scene: serde_json::Value = serde_json::from_str(&text).unwrap_or_else(|e| {
        eprintln!("parse {scene_path}: {e}");
        std::process::exit(1);
    });
    scene
        .get("enemies")
        .and_then(serde_json::Value::as_array)
        .cloned()
        .unwrap_or_default()
        .iter()
        .map(|enemy| {
            enemy
                .get("position")
                .and_then(serde_json::Value::as_array)
                .and_then(|a| {
                    Some([
                        a.first()?.as_f64()? as f32,
                        a.get(1)?.as_f64()? as f32,
                        a.get(2)?.as_f64()? as f32,
                    ])
                })
                .unwrap_or_else(|| {
                    eprintln!("enemy without position in {scene_path}");
                    std::process::exit(1);
                })
        })
        .collect()
}

fn assignments_json(positions: &[[f32; 3]], camera: [f32; 3]) -> String {
    let entries: Vec<String> = positions
        .iter()
        .enumerate()
        .map(|(index, position)| {
            format!(
                "{{\"index\":{index},\"frame\":{}}}",
                evaluate_directional(*position, camera)
            )
        })
        .collect();
    format!("[{}]", entries.join(","))
}

// --- Serve mode: consolidated authority over AnimationService -------------

/// Sprite metadata loaded from enemies.json (generated by dump-frame.mjs).
/// Contains both enemy sprites (handle + position + mobile_id) and animated
/// billboard sprites (handle + frame_count + fps).
struct SpriteMetadata {
    enemies: Vec<(u32, [f32; 3], u8)>, // (handle, position, mobile_id)
    animated_billboards: Vec<(u32, u32)>, // (handle, frame_count)
    /// Enemy atlas total frame count per mobile_id (8 * M).
    enemy_atlas_frames: std::collections::HashMap<u8, u32>,
}

fn load_sprite_metadata(path: &str) -> SpriteMetadata {
    let text = std::fs::read_to_string(path).unwrap_or_else(|e| {
        eprintln!("read {path}: {e}");
        std::process::exit(1);
    });
    let data: serde_json::Value = serde_json::from_str(&text).unwrap_or_else(|e| {
        eprintln!("parse {path}: {e}");
        std::process::exit(1);
    });

    let enemies = data
        .get("enemies")
        .and_then(serde_json::Value::as_array)
        .cloned()
        .unwrap_or_default()
        .iter()
        .map(|e| {
            let handle = e.get("handle").and_then(|v| v.as_u64()).unwrap_or(0) as u32;
            let pos = e
                .get("position")
                .and_then(serde_json::Value::as_array)
                .and_then(|a| {
                    Some([
                        a.first()?.as_f64()? as f32,
                        a.get(1)?.as_f64()? as f32,
                        a.get(2)?.as_f64()? as f32,
                    ])
                })
                .unwrap_or([0.0, 0.0, 0.0]);
            let mobile_id = e.get("mobileId").and_then(|v| v.as_u64()).unwrap_or(0) as u8;
            (handle, pos, mobile_id)
        })
        .collect();

    let animated_billboards = data
        .get("animatedBillboards")
        .and_then(serde_json::Value::as_array)
        .cloned()
        .unwrap_or_default()
        .iter()
        .map(|b| {
            let handle = b.get("handle").and_then(|v| v.as_u64()).unwrap_or(0) as u32;
            let frame_count = b.get("frameCount").and_then(|v| v.as_u64()).unwrap_or(1) as u32;
            (handle, frame_count)
        })
        .collect();

    let enemy_atlas_frames: std::collections::HashMap<u8, u32> = data
        .get("enemyAtlasFrames")
        .and_then(serde_json::Value::as_object)
        .map(|m| {
            m.iter()
                .filter_map(|(k, v)| {
                    let id = k.parse::<u8>().ok()?;
                    let count = v.as_u64()? as u32;
                    Some((id, count))
                })
                .collect()
        })
        .unwrap_or_default();

    SpriteMetadata {
        enemies,
        animated_billboards,
        enemy_atlas_frames,
    }
}

fn build_service(meta: &SpriteMetadata) -> AnimationService {
    let mut svc = AnimationService::new();
    for &(handle, position, mobile_id) in &meta.enemies {
        // Compute anim_frame_count from the atlas: the enemy atlas has
        // 8 orientations × M frames. We get the total from the atlas frame
        // count and divide by 8.
        let total = meta
            .enemy_atlas_frames
            .get(&mobile_id)
            .copied()
            .unwrap_or(8);
        let anim_frame_count = total / 8;
        svc.add_enemy(handle, position, mobile_id, anim_frame_count.max(1));
    }
    for &(handle, frame_count) in &meta.animated_billboards {
        svc.add_env(handle, frame_count);
    }
    svc
}

fn updates_json(updates: &[FrameUpdate]) -> String {
    let entries: Vec<String> = updates
        .iter()
        .map(|u| format!("{{\"handle\":{},\"frame\":{}}}", u.handle, u.frame))
        .collect();
    format!("[{}]", entries.join(","))
}

fn serve(meta_path: &str, addr: &str) {
    let meta = load_sprite_metadata(meta_path);
    let mut svc = build_service(&meta);

    // Resolve the navgrid path relative to the enemies.json file's location,
    // not the process cwd. The enemies.json lives at
    // <repo>/engine-render-check/generated/enemies.json, so the repo root is
    // 3 parents up. This ensures the serve endpoint works regardless of the
    // process working directory (R6641-1: launching from /tmp must not
    // silently disable patrol).
    let meta_dir = std::path::Path::new(meta_path)
        .parent() // generated/
        .and_then(|p| p.parent()) // engine-render-check/
        .and_then(|p| p.parent()) // repo root
        .unwrap_or(std::path::Path::new("."));
    let navgrid_path = meta_dir.join("content/projects/privateers-hold.navgrid.json");

    let mut patrol = {
        let nav_text = std::fs::read_to_string(&navgrid_path).unwrap_or_else(|e| {
            eprintln!(
                "fatal: navgrid not found at {}: {e}",
                navgrid_path.display()
            );
            std::process::exit(1);
        });
        let ng: serde_json::Value = serde_json::from_str(&nav_text).unwrap_or_else(|e| {
            eprintln!("fatal: navgrid parse error: {e}");
            std::process::exit(1);
        });
        let cells: Vec<(f64, f64, f64, f64)> = ng
            .get("cells")
            .and_then(serde_json::Value::as_array)
            .unwrap_or_else(|| {
                eprintln!("fatal: navgrid has no cells array");
                std::process::exit(1);
            })
            .iter()
            .filter_map(|c| c.as_array())
            .filter_map(|a| {
                Some((
                    a.first()?.as_f64()?,
                    a.get(1)?.as_f64()?,
                    a.get(2)?.as_f64()?,
                    a.get(3)?.as_f64()?,
                ))
            })
            .collect();

        // Ground spawns using navgrid.json's spawn array (task 6639
        // already computed the correct floor support per spawn).
        let nav_spawns = ng
            .get("spawns")
            .and_then(serde_json::Value::as_array)
            .cloned()
            .unwrap_or_default();
        let spawns: Vec<(u32, [f32; 3])> = meta
            .enemies
            .iter()
            .map(|&(handle, authored_pos, _)| {
                let grounded = nav_spawns
                    .iter()
                    .filter_map(|s| {
                        let sp = s.get("spawn")?.as_array()?;
                        let dx = sp.first()?.as_f64()? as f32 - authored_pos[0];
                        let dz = sp.get(2)?.as_f64()? as f32 - authored_pos[2];
                        let dy = sp.get(1)?.as_f64()? as f32 - authored_pos[1];
                        let d2 = dx * dx + dy * dy + dz * dz;
                        let ly = s.get("landingY")?.as_f64()? as f32;
                        Some((d2, ly))
                    })
                    .min_by(|a, b| a.0.partial_cmp(&b.0).unwrap())
                    .map(|(_, ly)| ly)
                    .unwrap_or(authored_pos[1]);
                (handle, [authored_pos[0], grounded, authored_pos[2]])
            })
            .collect();
        PatrolService::new(&cells, &spawns)
    };

    eprintln!(
        "patrol:      {} NPCs grounded and patrolling",
        meta.enemies.len()
    );

    let start = Instant::now();
    let mut last_elapsed = 0.0f32;

    eprintln!(
        "dagger-sprite-frames serving {} enemies + {} animated billboards on {addr}",
        meta.enemies.len(),
        meta.animated_billboards.len(),
    );

    let listener = TcpListener::bind(addr).unwrap_or_else(|e| {
        eprintln!("bind {addr}: {e}");
        std::process::exit(1);
    });

    for stream in listener.incoming() {
        let Ok(mut stream) = stream else { continue };
        let mut reader = BufReader::new(stream.try_clone().unwrap());
        let mut line = String::new();
        if reader.read_line(&mut line).is_err() {
            continue;
        }

        // Support both /updates?cam=x,y,z (new) and /assignments?cam=x,y,z (legacy)
        let camera = line
            .split_whitespace()
            .nth(1)
            .and_then(|path| {
                path.strip_prefix("/updates?cam=")
                    .or_else(|| path.strip_prefix("/assignments?cam="))
            })
            .and_then(parse_camera_opt);

        let (status, body) = match camera {
            Some(cam) => {
                // Advance elapsed time from wall-clock (the server owns timing).
                let now = start.elapsed().as_secs_f32() as f32;
                let dt = now - last_elapsed;
                last_elapsed = now;

                // 1. Advance patrol (if loaded): moves NPCs on walkable cells.
                let transform_json = {
                    let pos_updates = patrol.evaluate(dt);
                    // Push updated positions + is_moving to animation service.
                    svc.update_enemies(&patrol.positions());
                    // Build transform JSON for the flycam to apply as `update` ops.
                    let entries: Vec<String> = pos_updates
                        .iter()
                        .map(|u| {
                            format!(
                                "{{\"handle\":{},\"translation\":[{:?},{:?},{:?}]}}",
                                u.handle, u.translation[0], u.translation[1], u.translation[2]
                            )
                        })
                        .collect();
                    format!(",\"transforms\":[{}]", entries.join(","))
                };

                // 2. Evaluate animation (env flat + enemy directional frames).
                // Enemy positions/is_moving were just updated from patrol.
                let updates = svc.evaluate(dt, cam);
                (
                    "200 OK",
                    format!("{{\"updates\":{}{transform_json}}}", updates_json(&updates)),
                )
            }
            None => (
                "400 Bad Request",
                "{\"error\":\"expected /updates?cam=x,y,z\"}".into(),
            ),
        };

        let response = format!(
"HTTP/1.1 {status}\r\ncontent-type: application/json\r\naccess-control-allow-origin: *\r\ncontent-length: {}\r\nconnection: close\r\n\r\n{body}",
body.len()
);
        let _ = stream.write_all(response.as_bytes());
    }
}

fn main() {
    let mut args = std::env::args().skip(1);
    let path = args.next().unwrap_or_else(|| {
eprintln!(
"usage: dagger-sprite-frames <scene.json> <cam-x,cam-y,cam-z>...\n       dagger-sprite-frames <enemies.json> --serve <host:port>"
);
std::process::exit(2);
});
    let rest: Vec<String> = args.collect();

    if rest.first().map(String::as_str) == Some("--serve") {
        let addr = rest.get(1).map(String::as_str).unwrap_or("127.0.0.1:4193");
        serve(&path, addr);
        return;
    }

    // One-shot directional mode (scene.json + camera poses)
    let positions = load_enemy_positions(&path);
    if rest.is_empty() {
        eprintln!("at least one camera is required");
        std::process::exit(2);
    }
    let mut poses = Vec::new();
    for arg in &rest {
        let camera = parse_camera(arg);
        poses.push(format!(
            "{{\"camera\":[{:?},{:?},{:?}],\"assignments\":{}}}",
            camera[0],
            camera[1],
            camera[2],
            assignments_json(&positions, camera)
        ));
    }
    println!(
        "{{\"enemyCount\":{},\"poses\":[{}]}}",
        positions.len(),
        poses.join(",")
    );
}
